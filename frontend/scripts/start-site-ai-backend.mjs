import { buildSiteAiFixtureEnvironment } from './site-ai-fixture.mjs';
import { mkdtemp, mkdir, writeFile } from 'node:fs/promises';
import { randomBytes } from 'node:crypto';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const root = await mkdtemp(join(tmpdir(), 'qunthink-site-ai-e2e-'));
const data = join(root, 'data');
await mkdir(data);
const emptyEnv = join(root, 'empty.env');
await writeFile(emptyEnv, '');
const isolated = buildSiteAiFixtureEnvironment(process.env, data, emptyEnv, randomBytes(32).toString('base64'));
for (const key of Object.keys(process.env)) delete process.env[key];
Object.assign(process.env, isolated);
const { initializeEmptyInstallation } = await import('../../backend/src/models/db.js');
await initializeEmptyInstallation();
await import('../../backend/src/index.js');
